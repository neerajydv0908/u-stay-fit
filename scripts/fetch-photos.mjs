// Downloads the site's photographs once so visitors' browsers never contact a third-party
// image host. Run from the project root: npm run photos:fetch
// Files land in client/public/photos and the manifest client/src/photos.local.js is rewritten;
// the app switches to the local copies automatically and the server drops the image host
// from its content-security policy.
import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { photoSources, unsplashUrl } from '../client/src/data.js';

const dir = new URL('../client/public/photos/', import.meta.url);
await mkdir(dir, { recursive: true });
const manifest = {};
let downloaded = 0;
for (const [key, [id, width]] of Object.entries(photoSources)) {
  // Already downloaded earlier: keep the existing file untouched.
  if (existsSync(new URL(`${key}.jpg`, dir))) {
    manifest[key] = `/photos/${key}.jpg`;
    continue;
  }
  const url = unsplashUrl(id, width);
  process.stdout.write(`${key} ← ${url}\n`);
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${key}: HTTP ${response.status}`);
  const type = response.headers.get('content-type') || '';
  if (!type.startsWith('image/')) throw new Error(`${key}: unexpected content type ${type}`);
  await writeFile(new URL(`${key}.jpg`, dir), Buffer.from(await response.arrayBuffer()));
  manifest[key] = `/photos/${key}.jpg`;
  downloaded += 1;
}
// Written in the project's Prettier style so `npm run format` has nothing to change.
const entries = Object.entries(manifest)
  .map(([key, file]) => `  ${key}: '${file}',`)
  .join('\n');
await writeFile(
  new URL('../client/src/photos.local.js', import.meta.url),
  `// Generated by \`npm run photos:fetch\`. Maps photo keys to files under client/public/photos.\n// An empty object means the original Unsplash URLs in data.js are used.\nexport default {\n${entries}\n};\n`,
);
console.log(
  `Downloaded ${downloaded} new photo(s); ${Object.keys(manifest).length} photos in total. Restart the dev server to see them.`,
);
